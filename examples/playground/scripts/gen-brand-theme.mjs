// Generates src/brand-theme.css — the playground's proof that the color
// vocabulary is DS-declared, not fixed: a scoped theme declaring a novel
// `brand` role and a declared custom token, compiled by @sigx/zero-kit
// exactly like a full design system. Re-run with `pnpm gen:brand`.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { compileTokensCss, defineTokens } from '@sigx/zero-kit';

const tokens = defineTokens({
    roles: { brand: { description: 'playground demo role — not in any built-in vocabulary' } },
    custom: { 'brand-glow': { description: 'halo behind brand chips', syntax: '<color>' } },
    themes: {
        brand: {
            colorScheme: 'light',
            colors: {
                'base-100': 'oklch(98% 0.01 320)',
                'base-200': 'oklch(94% 0.02 320)',
                'base-300': 'oklch(89% 0.03 320)',
                'base-content': 'oklch(25% 0.05 320)',
                brand: 'oklch(55% 0.25 320)',
                'brand-content': 'oklch(98% 0.01 320)',
            },
            custom: { 'brand-glow': 'oklch(75% 0.18 320)' },
        },
    },
    defaultLight: 'brand',
});

const out = fileURLToPath(new URL('../src/brand-theme.css', import.meta.url));
await writeFile(out, `/* Generated by scripts/gen-brand-theme.mjs — do not edit. */\n${compileTokensCss(tokens)}`);
console.log('[playground] wrote src/brand-theme.css');
