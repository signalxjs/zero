// Regenerates src/resolve/css-properties.ts from @webref/css — the W3C's
// machine-readable extraction of every CSS specification (#51).
//
// The list is checked in rather than read at validation time so that the
// kit's runtime graph stays free of the dependency and the rule's verdicts
// are reproducible from the tree alone. `__tests__/css-properties.test.ts`
// regenerates in memory and compares, so a stale file is a failing test
// rather than a trap; @webref/css is pinned exact (and dependabot-ignored)
// so the list moves only when someone runs this on purpose:
//
//     pnpm --filter @sigx/zero-kit gen:css-properties
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { listAll } from '@webref/css';

// vitest hands the module a bare path for import.meta.url; Node hands a file: URL.
const here = import.meta.url.startsWith('file:') ? import.meta.url : pathToFileURL(import.meta.url).href;
const require = createRequire(here);
const { version } = JSON.parse(await readFile(require.resolve('@webref/css/package.json'), 'utf8'));

/** The sorted, de-duplicated property names webref knows, kebab-case as written in the specs. */
export async function collectCssProperties() {
    const { properties } = await listAll();
    const names = new Set(properties.map((p) => p.name));
    for (const name of names) {
        if (!/^-?[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) {
            throw new Error(`[zero-kit] @webref/css lists a property that is not kebab-case: "${name}"`);
        }
    }
    return { version, names: [...names].sort() };
}

/** The file content, so the test and the script cannot disagree on formatting. */
export function renderCssProperties({ version, names }) {
    const rows = names.map((n) => `    '${n}',`).join('\n');
    return `// GENERATED by scripts/gen-css-properties.mjs from @webref/css ${version} — do not edit.
// Regenerate: pnpm --filter @sigx/zero-kit gen:css-properties
//
// Every property name the CSS specifications define, kebab-case, including
// the logical properties, the -webkit- legacy aliases the compat spec
// records, and \`all\`. \`validate-recipes\` reads it to catch a misspelled
// declaration key (#51) — the browser drops such a declaration silently, so
// nothing else in the pipeline would ever say.

export const CSS_PROPERTIES_SOURCE = '@webref/css ${version}';

export const CSS_PROPERTIES: ReadonlySet<string> = new Set([
${rows}
]);
`;
}

if (process.argv[1] && here === pathToFileURL(process.argv[1]).href) {
    const out = new URL('../src/resolve/css-properties.ts', here);
    const data = await collectCssProperties();
    await writeFile(out, renderCssProperties(data));
    console.log(`[zero-kit] wrote ${data.names.length} CSS property names from @webref/css ${data.version}`);
}
